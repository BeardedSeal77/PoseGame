using System;

public enum PoseJointId
{
    Nose = 0,
    LeftEye = 1,
    RightEye = 2,
    LeftEar = 3,
    RightEar = 4,
    LeftShoulder = 5,
    RightShoulder = 6,
    LeftElbow = 7,
    RightElbow = 8,
    LeftWrist = 9,
    RightWrist = 10,
    LeftHip = 11,
    RightHip = 12,
    LeftKnee = 13,
    RightKnee = 14,
    LeftAnkle = 15,
    RightAnkle = 16,
}

public static class PoseJointIdUtility
{
    public const int JointCount = 17;

    public static bool IsValidIndex(int index)
    {
        return index >= 0 && index < JointCount;
    }
}